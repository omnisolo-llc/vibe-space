(function () {
  'use strict';

  var dealRadar = {
    id: 'deal-radar',
    name: 'True Deal Radar',
    wish: 'Highlight wishlist items at least 20% below typical price',
    version: 1,
    needs: ['wishlist.deals'],
    refresh: 2000,
    source: [
      'function invoke(input) {',
      '  var MIN_DISCOUNT = 0.2;',
      '  var TOP_LIMIT = 5;',
      "  var rows = (input.data && input.data['wishlist.deals']) || [];",
      '  if (!rows.length) {',
      '    return {',
      '      state: input.state,',
      "      view: { type: 'column', children: [",
      "        { type: 'heading', text: 'True deal radar' },",
      "        { type: 'badge', text: 'No listed wishlist items', tone: 'warn' }",
      '      ] }',
      '    };',
      '  }',
      '  var sorted = rows.slice().sort(function (a, b) {',
      '    return b.discountFraction - a.discountFraction;',
      '  });',
      '  var matches = [];',
      '  for (var i = 0; i < sorted.length; i++) {',
      '    if (sorted[i].discountFraction >= MIN_DISCOUNT) matches.push(sorted[i]);',
      '  }',
      '  var shown = sorted.slice(0, TOP_LIMIT);',
      '  var minPct = Math.round(MIN_DISCOUNT * 100);',
      '  var children = [',
      "    { type: 'heading', text: 'True deal radar' },",
      "    { type: 'text', text: matches.length + ' of ' + rows.length + ' items at least ' + minPct + '% below typical', tone: matches.length > 0 ? 'ok' : 'warn' }",
      '  ];',
      '  for (var j = 0; j < shown.length; j++) {',
      '    var row = shown[j];',
      '    var pct = Math.round(row.discountFraction * 100);',
      "    var tone = !row.inStock ? 'warn' : (row.discountFraction >= MIN_DISCOUNT ? 'ok' : 'default');",
      "    var stockLabel = row.inStock ? 'In stock' : 'Backordered';",
      '    children.push({',
      "      type: 'bar',",
      '      label: row.item,',
      '      value: row.discountFraction,',
      '      max: 0.5,',
      "      caption: '$' + row.currentUsd + ' vs $' + row.typicalUsd + ' (' + pct + '% off · ' + stockLabel + ')',",
      '      tone: tone',
      '    });',
      '  }',
      '  return { state: input.state, view: { type: \'column\', children: children } };',
      '}'
    ].join('\n')
  };

  var dealRadarV2 = {
    id: 'deal-radar',
    name: 'True Deal Radar',
    wish: 'Show only the top 3 deals at 25% off or better',
    version: 2,
    needs: ['wishlist.deals'],
    refresh: 2000,
    source: [
      'function invoke(input) {',
      '  var MIN_DISCOUNT = 0.25;',
      '  var TOP_LIMIT = 3;',
      "  var rows = (input.data && input.data['wishlist.deals']) || [];",
      '  if (!rows.length) {',
      '    return {',
      '      state: input.state,',
      "      view: { type: 'column', children: [",
      "        { type: 'heading', text: 'True deal radar · top ' + TOP_LIMIT },",
      "        { type: 'badge', text: 'No listed wishlist items', tone: 'warn' }",
      '      ] }',
      '    };',
      '  }',
      '  var sorted = rows.slice().sort(function (a, b) {',
      '    return b.discountFraction - a.discountFraction;',
      '  });',
      '  var matches = [];',
      '  for (var i = 0; i < sorted.length; i++) {',
      '    if (sorted[i].discountFraction >= MIN_DISCOUNT) matches.push(sorted[i]);',
      '  }',
      '  var shown = (matches.length ? matches : sorted).slice(0, TOP_LIMIT);',
      '  var minPct = Math.round(MIN_DISCOUNT * 100);',
      '  var children = [',
      "    { type: 'heading', text: 'True deal radar · top ' + TOP_LIMIT },",
      "    { type: 'text', text: matches.length + ' verified drops at ' + minPct + '%+ below 90d baseline', tone: matches.length > 0 ? 'ok' : 'warn' }",
      '  ];',
      '  for (var j = 0; j < shown.length; j++) {',
      '    var row = shown[j];',
      '    var pct = Math.round(row.discountFraction * 100);',
      "    var tone = !row.inStock ? 'warn' : (row.discountFraction >= MIN_DISCOUNT ? 'ok' : 'default');",
      '    children.push({',
      "      type: 'bar',",
      '      label: row.item,',
      '      value: row.discountFraction,',
      '      max: 0.5,',
      "      caption: '$' + row.currentUsd + ' (typ. $' + row.typicalUsd + ' · ' + pct + '% off)',",
      '      tone: tone',
      '    });',
      '  }',
      '  return { state: input.state, view: { type: \'column\', children: children } };',
      '}'
    ].join('\n')
  };

  var itemPriceWatch = {
    id: 'item-price-watch',
    name: '90-Day Price Watch',
    wish: 'Track 90-day price history for one wishlist item',
    version: 1,
    needs: ['wishlist.deals'],
    refresh: 2000,
    source: [
      'function invoke(input) {',
      '  var st = input.state && typeof input.state === "object" ? Object.assign({}, input.state) : {};',
      "  if (input.command === 'clear-target') st.allMode = true;",
      "  if (input.command === 'restore-target') st.allMode = false;",
      "  var rows = (input.data && input.data['wishlist.deals']) || [];",
      '  var target = input.args && input.args.item;',
      '  var match = null;',
      '  if (!st.allMode && target && target.sealed) {',
      '    for (var i = 0; i < rows.length; i++) {',
      '      if (rows[i].item && rows[i].item.sealed === target.sealed) {',
      '        match = rows[i];',
      '        break;',
      '      }',
      '    }',
      '  }',
      '  if (!st.allMode && target && target.sealed && !match) {',
      '    var last = st.lastReading;',
      '    var children = [',
      "      { type: 'heading', text: '90-Day Price Watch' },",
      "      { type: 'badge', text: 'Target item delisted', tone: 'warn' }",
      '    ];',
      '    if (last) {',
      '      children.push({',
      "        type: 'row',",
      '        children: [',
      "          { type: 'stat', label: 'Last price', value: '$' + last.currentUsd },",
      "          { type: 'stat', label: '90d typical', value: '$' + last.typicalUsd }",
      '        ]',
      '      });',
      '      if (Array.isArray(last.priceHistory) && last.priceHistory.length >= 2) {',
      "        children.push({ type: 'sparkline', values: last.priceHistory, tone: 'warn' });",
      '      }',
      '    } else {',
      "      children.push({ type: 'text', text: 'This listing is currently unavailable from the tracker.' });",
      '    }',
      "    children.push({ type: 'button', text: 'Show all listed deals', command: 'clear-target' });",
      '    return { state: st, view: { type: \'column\', children: children } };',
      '  }',
      '  var active = match || rows[0];',
      '  if (!active) {',
      '    return {',
      '      state: st,',
      "      view: { type: 'column', children: [",
      "        { type: 'heading', text: '90-Day Price Watch' },",
      "        { type: 'badge', text: 'No wishlist listings active', tone: 'warn' }",
      '      ] }',
      '    };',
      '  }',
      '  if (match) {',
      '    st.lastReading = {',
      '      currentUsd: match.currentUsd,',
      '      typicalUsd: match.typicalUsd,',
      '      discountFraction: match.discountFraction,',
      '      priceHistory: Array.isArray(match.priceHistory) ? match.priceHistory.slice() : []',
      '    };',
      '  }',
      '  var pct = Math.round(active.discountFraction * 100);',
      "  var tone = active.discountFraction >= 0.2 ? 'ok' : 'warn';",
      '  var out = [',
      '    {',
      "      type: 'row',",
      '      children: [',
      "        { type: 'heading', text: active.item },",
      "        { type: 'badge', text: pct + '% below 90d avg', tone: tone }",
      '      ]',
      '    },',
      '    {',
      "      type: 'row',",
      '      children: [',
      "        { type: 'stat', label: 'Current price', value: '$' + active.currentUsd, tone: tone },",
      "        { type: 'stat', label: '90d typical', value: '$' + active.typicalUsd }",
      '      ]',
      '    },',
      "    { type: 'text', text: ['Seller: ', active.seller] }",
      '  ];',
      '  if (Array.isArray(active.priceHistory) && active.priceHistory.length >= 2) {',
      "    out.push({ type: 'sparkline', values: active.priceHistory, tone: tone });",
      '  }',
      '  if (st.allMode && target) {',
      "    out.push({ type: 'button', text: 'Back to watched item', command: 'restore-target' });",
      '  }',
      '  return { state: st, view: { type: \'column\', children: out } };',
      '}'
    ].join('\n')
  };

  window.SHOP_VIBES = {
    dealRadar: dealRadar,
    dealRadarV2: dealRadarV2,
    itemPriceWatch: itemPriceWatch,
    wishes: [
      {
        text: 'Highlight wishlist items at least 20% below typical price',
        vibe: dealRadar
      },
      {
        text: 'Show only the top 3 deals at 25% off or better',
        vibe: dealRadarV2,
        remixOf: 'deal-radar'
      },
      {
        text: 'Track 90-day price history for one wishlist item',
        vibe: itemPriceWatch
      }
    ]
  };
})();
