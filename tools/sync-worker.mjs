import {readFile, writeFile} from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const worker = await readFile(new URL('web/worker.js', root), 'utf8');
const generated = "// Generated by tools/sync-worker.mjs. Edit web/worker.js.\nconst vibeWorkerSource = r'''\n" + worker + "''';\n";
const target = new URL('flutter/lib/worker_source.dart', root);
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== generated) throw Error('Run node tools/sync-worker.mjs');
} else await writeFile(target, generated);
